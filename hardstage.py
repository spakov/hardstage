MARKER_TEXT = f"""\
This directory is managed by {PROG}. Files in it that are not selected by
the {PROG} configuration are deleted on each run. This file also serves as
the lock that keeps two runs from overlapping.
"""


def _write_marker(target):
    with open(os.path.join(target, MARKER_NAME), "w", encoding="utf-8") as fh:
        fh.write(MARKER_TEXT)


def validate_target(target, home):
    if target == home or home.startswith(target.rstrip(os.sep) + os.sep) or target == os.sep:
        raise Fatal(f"refusing to use {target} as the target: it is (or "
                    "contains) your home directory")
    if os.path.lexists(target) and not os.path.isdir(target):
        raise Fatal(f"target {target} exists and is not a directory")


def prepare_target(target, dry_run, log):
    """Create/verify the target, take the lock, and probe for hard-link support.

    Returns (target st_dev or None, lock file handle or None).
    """
    marker = os.path.join(target, MARKER_NAME)
    if not os.path.exists(target):
        log.info(f"create target: {target}")
        if dry_run:
            return None, None
        os.makedirs(target, mode=0o700)
        _write_marker(target)
    elif not os.path.exists(marker):
        if os.listdir(target):
            raise Fatal(
                f"{target} is not empty and has no {MARKER_NAME} marker, so "
                f"{PROG} won't manage it (it deletes anything not in its "
                f"configuration). Use an empty or new directory, or create "
                f"{marker} yourself if you're sure.")
        log.info(f"initialise target: {target}")
        if dry_run:
            return os.stat(target).st_dev, None
        _write_marker(target)

    lock = open(marker, "a")
    try:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except BlockingIOError:
        lock.close()
        raise Busy() from None

    if not dry_run:
        probe = os.path.join(target, MARKER_NAME + ".probe")
        _unlink_quiet(probe)
        try:
            os.link(marker, probe)
        except OSError as e:
            lock.close()
            raise Fatal(
                f"cannot create hard links in {target} ({e.strerror}). The "
                f"target must be on a filesystem that supports hard links "
                f"(not FAT/exFAT, most network or cloud mounts, ...), and on "
                f"the same filesystem as the files being staged.") from None
        finally:
            _unlink_quiet(probe)
    return os.stat(target).st_dev, lock


class Stager:
    def __init__(self, home, target, log, dry_run, target_dev):
        self.home = home
        self.target = target
        self.log = log
        self.dry_run = dry_run
        self.target_dev = target_dev
        self.ready_dirs = {""}
        self.counts = {"linked": 0, "relinked": 0, "unchanged": 0, "removed": 0}
        self.errors = 0
        self.cross_device = []

    def _src(self, rel):
        return os.path.join(self.home, rel)

    def _dst(self, rel):
        return os.path.join(self.target, rel) if rel else self.target

    def _tmp_for(self, dst):
        return os.path.join(os.path.dirname(dst), f".{PROG}-{os.getpid()}.tmp")

    def ensure_dir(self, rel):
        if rel in self.ready_dirs:
            return
        self.ensure_dir(rel.rpartition("/")[0])
        dst = self._dst(rel)
        try:
            mode = stat.S_IMODE(os.lstat(self._src(rel)).st_mode)
        except OSError:
            mode = 0
        mode |= stat.S_IRWXU  # we must be able to manage our own tree
        st = _lstat(dst)
        if st is not None and not stat.S_ISDIR(st.st_mode):
            self.log.info(f"replace with directory: {rel}")
            if not self.dry_run:
                os.unlink(dst)
            st = None
        if st is None:
            self.log.info(f"mkdir: {rel}/")
            if not self.dry_run:
                os.mkdir(dst, mode)
                os.chmod(dst, mode)  # mkdir is subject to umask
        elif stat.S_IMODE(st.st_mode) != mode and not self.dry_run:
            os.chmod(dst, mode)
        self.ready_dirs.add(rel)

    def stage(self, rel, item):
        if (item.kind == "file" and self.target_dev is not None
                and item.dev != self.target_dev):
            self.cross_device.append(rel)
            return
        dst = self._dst(rel)
        tmp = None
        try:
            self.ensure_dir(rel.rpartition("/")[0])
            st = _lstat(dst)
            if st is not None:
                if (item.kind == "file" and stat.S_ISREG(st.st_mode)
                        and (st.st_dev, st.st_ino) == (item.dev, item.ino)):
                    self.counts["unchanged"] += 1
                    return
                if (item.kind == "link" and stat.S_ISLNK(st.st_mode)
                        and os.readlink(dst) == item.linkto):
                    self.counts["unchanged"] += 1
                    return
            action = "linked" if st is None else "relinked"
            self.log.info(f"{'link' if st is None else 'relink'}: {rel}")
            if not self.dry_run:
                if st is not None and stat.S_ISDIR(st.st_mode):
                    shutil.rmtree(dst)
                # Build the new entry beside the old one and rename it into
                # place, so the target never momentarily lacks the file.
                tmp = self._tmp_for(dst)
                _unlink_quiet(tmp)
                if item.kind == "file":
                    os.link(self._src(rel), tmp, follow_symlinks=False)
                else:
                    os.symlink(item.linkto, tmp)
                os.replace(tmp, dst)
            self.counts[action] += 1
        except OSError as e:
            if e.errno == errno.EXDEV:
                self.cross_device.append(rel)
            else:
                self.log.error(f"{rel}: {e.strerror or e}")
                self.errors += 1
        finally:
            # Also covers rename() being a no-op when tmp and dst are
            # already the same inode.
            if tmp is not None:
                _unlink_quiet(tmp)

    def prune(self, items, protected, keeps):
        if not os.path.isdir(self.target):
            return
        retained = set()

        def retain(rel):
            while rel and rel not in retained:
                retained.add(rel)
                rel = rel.rpartition("/")[0]

        dirs = []
        stack = [""]
        while stack:
            drel = stack.pop()
            try:
                it = os.scandir(self._dst(drel))
            except OSError as e:
                self.log.error(f"cannot read {self._dst(drel)}: {e.strerror}")
                self.errors += 1
                retain(drel)
                continue
            with it:
                for entry in it:
                    rel = join_rel(drel, entry.name)
                    if ((not drel and entry.name in RESERVED_NAMES)
                            or any(is_under(rel, p) for p in protected)
                            or any(k.fullmatch(rel) for k in keeps)):
                        retain(rel)
                        continue
                    try:
                        is_dir = entry.is_dir(follow_symlinks=False)
                    except OSError:
                        is_dir = False
                    if is_dir:
                        dirs.append(rel)
                        stack.append(rel)
                    elif rel in items:
                        retain(rel)
                    else:
                        self.log.info(f"remove: {rel}")
                        if self.dry_run:
                            self.counts["removed"] += 1
                            continue
                        try:
                            os.unlink(entry.path)
                            self.counts["removed"] += 1
                        except OSError as e:
                            self.log.error(f"cannot remove {entry.path}: {e.strerror}")
                            self.errors += 1
                            retain(rel)

        for rel in sorted(dirs, key=lambda r: r.count("/"), reverse=True):
            if rel in retained:
                continue
            self.log.info(f"rmdir: {rel}/")
            if self.dry_run:
                continue
            try:
                os.rmdir(self._dst(rel))
            except OSError as e:
                if e.errno not in (errno.ENOTEMPTY, errno.EEXIST):
                    self.log.error(f"cannot remove {self._dst(rel)}: {e.strerror}")
                    self.errors += 1


