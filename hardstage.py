def default_config_path():
    env = os.environ.get("HARDSTAGE_CONFIG")
    if env:
        return os.path.expanduser(env)
    base = os.environ.get("XDG_CONFIG_HOME") or os.path.expanduser("~/.config")
    return os.path.join(base, PROG, "config")


def cmd_init(config_path):
    if os.path.exists(config_path):
        raise Fatal(f"{config_path} already exists")
    os.makedirs(os.path.dirname(config_path), exist_ok=True)
    with open(config_path, "w", encoding="utf-8") as fh:
        fh.write(EXAMPLE_CONFIG)
    print(f"wrote {config_path}; edit it, then run '{PROG} list' to check "
          f"the selection")
    return EXIT_OK


def cmd_list(home, target, matcher, log):
    result = scan(home, matcher, target, log)
    total = 0
    for rel in sorted(result.items):
        item = result.items[rel]
        if item.kind == "link":
            print(f"{rel} -> {item.linkto}")
        else:
            print(rel)
            total += item.size
    print(f"{len(result.items)} entries, {human_size(total)}", file=sys.stderr)
    return EXIT_PARTIAL if result.errors else EXIT_OK


def cmd_sync(home, target, config, matcher, log, dry_run):
    target_dev, lock = prepare_target(target, dry_run, log)
    try:
        if target_dev is not None and os.stat(home).st_dev != target_dev:
            log.warn(f"{target} is on a different filesystem than your home "
                     "directory; files there cannot be hard-linked into it")
        result = scan(home, matcher, target, log)
        stager = Stager(home, target, log, dry_run, target_dev)
        for rel in sorted(result.items):
            stager.stage(rel, result.items[rel])
        errors = result.errors + stager.errors
        if stager.cross_device:
            n = len(stager.cross_device)
            log.error(f"{n} file(s) are on a different filesystem than "
                      f"{target} and can't be hard-linked "
                      f"(first: ~/{stager.cross_device[0]}). Move the target "
                      f"to that filesystem, or exclude them.")
            errors += 1
        stager.prune(result.items, result.protected, config.keeps)
        if os.path.isdir(target):
            write_readme(target, config.path, home, dry_run, log)
        c = stager.counts
        log.info(f"{'dry run: ' if dry_run else ''}{c['linked']} linked, "
                 f"{c['relinked']} relinked, {c['unchanged']} unchanged, "
                 f"{c['removed']} removed, {errors} error(s)")
        return EXIT_PARTIAL if errors else EXIT_OK
    finally:
        if lock is not None:
            lock.close()


def main(argv=None):
    parser = argparse.ArgumentParser(
        prog=PROG,
        description="Mirror selected files from your home directory into a "
                    "staging directory using hard links, ready for backup.")
    parser.add_argument("command", nargs="?", default="sync",
                        choices=("sync", "list", "init"),
                        help="sync (default): update the staging directory; "
                             "list: show what would be staged; "
                             "init: write an example configuration")
    parser.add_argument("-c", "--config", metavar="FILE",
                        help="configuration file (default: $HARDSTAGE_CONFIG "
                             "or $XDG_CONFIG_HOME/hardstage/config)")
    parser.add_argument("-t", "--target", metavar="DIR",
                        help="staging directory (overrides @target)")
    parser.add_argument("-n", "--dry-run", action="store_true",
                        help="show what would change without changing it")
    parser.add_argument("-v", "--verbose", action="store_true",
                        help="report every change and a summary")
    parser.add_argument("-q", "--quiet", action="store_true",
                        help="suppress warnings (errors are still reported)")
    parser.add_argument("--version", action="version",
                        version=f"%(prog)s {__version__}")
    args = parser.parse_args(argv)

    log = Log(verbose=args.verbose or args.dry_run, quiet=args.quiet)
    config_path = os.path.abspath(args.config or default_config_path())
    try:
        if args.command == "init":
            return cmd_init(config_path)
        config = parse_config(config_path)
        home = os.path.realpath(os.path.expanduser("~"))
        target = expand_path(args.target or config.target or DEFAULT_TARGET, home)
        validate_target(target, home)
        matcher = Matcher(config.rules)
        if args.command == "list":
            return cmd_list(home, target, matcher, log)
        return cmd_sync(home, target, config, matcher, log, args.dry_run)
    except Fatal as e:
        log.error(str(e))
        return EXIT_FATAL
    except Busy:
        log.warn("another run is in progress; nothing done")
        return EXIT_BUSY
    except OSError as e:
        log.error(str(e))
        return EXIT_FATAL


if __name__ == "__main__":
    sys.exit(main())
