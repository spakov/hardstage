_GLOB_CHARS = frozenset("*?[\\")


def glob_to_regex(pattern):
    """Translate a gitignore-style glob into a regex used with fullmatch().

    *   anything except "/"
    ?   one character except "/"
    []  character class ("!" or "^" negates)
    **  as a whole path component: zero or more directories
    """
    out = []
    i, n = 0, len(pattern)
    while i < n:
        c = pattern[i]
        if c == "*":
            j = i
            while j < n and pattern[j] == "*":
                j += 1
            whole = (j - i >= 2
                     and (i == 0 or pattern[i - 1] == "/")
                     and (j == n or pattern[j] == "/"))
            if whole and j == n:
                out.append(".*")
                i = j
            elif whole:
                out.append("(?:.*/)?")
                i = j + 1
            else:
                out.append("[^/]*")
                i = j
        elif c == "?":
            out.append("[^/]")
            i += 1
        elif c == "[":
            j = i + 1
            if j < n and pattern[j] in "!^":
                j += 1
            if j < n and pattern[j] == "]":
                j += 1
            while j < n and pattern[j] != "]":
                j += 1
            if j >= n:
                out.append(re.escape(c))
                i += 1
            else:
                body = pattern[i + 1:j]
                negate = body[0] in "!^"
                if negate:
                    body = body[1:]
                body = body.replace("\\", "\\\\").replace("[", "\\[")
                out.append("[" + ("^" if negate else "") + body + "]")
                i = j + 1
        elif c == "\\" and i + 1 < n:
            out.append(re.escape(pattern[i + 1]))
            i += 2
        else:
            out.append(re.escape(c))
            i += 1
    return re.compile("".join(out), re.DOTALL)


class Rule:
    __slots__ = ("index", "include", "anchored", "dir_only", "regex",
                 "prefix", "text", "where")

    def __init__(self, index, include, anchored, dir_only, regex, prefix,
                 text, where):
        self.index = index
        self.include = include
        self.anchored = anchored
        self.dir_only = dir_only
        self.regex = regex
        self.prefix = prefix
        self.text = text
        self.where = where

    def matches_self(self, rel, name, is_dir):
        if self.dir_only and not is_dir:
            return False
        return self.regex.fullmatch(rel if self.anchored else name) is not None


def _split_pattern(text, where):
    pattern = text
    if pattern.startswith("~/"):
        pattern = pattern[2:]
    dir_only = pattern.endswith("/")
    leading_slash = pattern.startswith("/")
    pattern = pattern.strip("/")
    comps = pattern.split("/") if pattern else []
    if not comps:
        raise Fatal(f"{where}: empty pattern {text!r}")
    if any(c in ("", ".", "..") for c in comps):
        raise Fatal(f"{where}: {text!r}: empty, '.' and '..' path "
                    "components are not allowed")
    return comps, dir_only, leading_slash


def parse_rule(text, include, index, where):
    comps, dir_only, leading_slash = _split_pattern(text, where)
    prefix = []
    for c in comps:
        if _GLOB_CHARS.intersection(c):
            break
        prefix.append(c)
    return Rule(
        index=index,
        include=include,
        # Includes are always relative to ~ (walking all of ~ to find a bare
        # name would be slow and surprising). Excludes without a "/" match a
        # name at any depth, like .gitignore.
        anchored=include or leading_slash or len(comps) > 1,
        dir_only=dir_only,
        regex=glob_to_regex("/".join(comps)),
        prefix="/".join(prefix),
        text=text,
        where=where,
    )


class Config:
    def __init__(self, path, rules, keeps, target):
        self.path = path
        self.rules = rules
        self.keeps = keeps
        self.target = target


def parse_config(path):
    try:
        fh = open(path, encoding="utf-8")
    except FileNotFoundError:
        raise Fatal(f"no configuration file at {path} "
                    f"(run '{PROG} init' to create one)") from None
    except OSError as e:
        raise Fatal(f"cannot read {path}: {e.strerror}") from None

    rules, keeps, target = [], [], None
    with fh:
        for lineno, raw in enumerate(fh, 1):
            where = f"{path}:{lineno}"
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            if line.startswith("@"):
                bits = line[1:].split(None, 1)
                name = bits[0] if bits else ""
                arg = bits[1].strip() if len(bits) > 1 else ""
                if name not in ("target", "keep"):
                    raise Fatal(f"{where}: unknown directive '@{name}'")
                if not arg:
                    raise Fatal(f"{where}: @{name} needs an argument")
                if name == "target":
                    target = arg
                else:
                    comps, _, _ = _split_pattern(arg, where)
                    keeps.append(glob_to_regex("/".join(comps)))
                continue
            include = True
            if line.startswith("!"):
                include = False
                line = line[1:].strip()
            elif line[0] == "\\" and len(line) > 1 and line[1] in "#!@":
                line = line[1:]
            rules.append(parse_rule(line, include, len(rules), where))
    return Config(path, rules, keeps, target)


class Matcher:
    """Last-matching-rule-wins evaluation over a path and its ancestors.

    `best` values are rule indices (-1 for "no rule matched"). A path's best
    is the highest-index rule matching the path itself or any ancestor, so it
    can be computed incrementally while walking down the tree.
    """

    def __init__(self, rules):
        self.rules = rules
        self.includes = [r for r in rules if r.include]

    def best(self, rel, name, is_dir, inherited):
        for rule in reversed(self.rules):
            if rule.index <= inherited:
                break
            if rule.matches_self(rel, name, is_dir):
                return rule.index
        return inherited

    def best_for(self, rel, is_dir):
        parts = rel.split("/")
        best = -1
        for k in range(1, len(parts) + 1):
            best = self.best("/".join(parts[:k]), parts[k - 1],
                             is_dir if k == len(parts) else True, best)
        return best

    def included(self, best):
        return best >= 0 and self.rules[best].include

    def may_include_below(self, rel, best):
        """Could a later include rule still match something beneath `rel`?"""
        for r in self.includes:
            if r.index > best and (is_under(r.prefix, rel) or is_under(rel, r.prefix)):
                return True
        return False

    def roots(self):
        roots = []
        for p in sorted({r.prefix for r in self.includes}, key=len):
            if not any(is_under(p, q) for q in roots):
                roots.append(p)
        return roots


