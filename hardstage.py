def render_readme(target, config_path, home):
    t = display(target, home)
    c = display(config_path, home)
    return f"""{README_SIGNATURE}
# About this directory

This is a **backup staging directory**. It is created and kept up to date by
`{PROG}`, a small tool that gathers a hand-picked selection of files from your
home directory into one place, so a backup tool (cloud sync, rsync to a NAS,
a burned disc, ...) only has to deal with this one folder.

## Where things came from

Paths here mirror your home directory: `{t}/.config/example.conf` is
`~/.config/example.conf`.

What gets staged is listed in `{c}`. Edit that file to change the
selection, then run `{PROG}` (or wait for its next scheduled run).

## These are hard links, not copies

Every file here is the *same file* as its original in your home directory,
reachable under a second name. That means:

- **Editing a file here edits the original.** Treat this directory as
  read-only.
- Deleting something here does not delete the original, and `{PROG}` puts it
  back on its next run.
- It takes up almost no extra disk space.
- Anything that *writes into* this directory (a two-way sync client, or
  restoring a backup straight into it) is writing into your real files.
  Back this directory up **one way only**.

## Restoring

Copy files from a backup of this directory back to the same paths under your
home directory, for example:

    rsync -a --dry-run --exclude=/README.md --exclude=/{MARKER_NAME} BACKUP_COPY/ ~/

Remove `--dry-run` once the output looks right. Close the applications that
own the files (mail client, browser, ...) first.

## Housekeeping files

- `README.md`: this file. It is regenerated automatically; delete its first
  line if you want to edit it yourself.
- `{MARKER_NAME}`: marks this directory as managed by `{PROG}` and serves as
  its lock. Without it, `{PROG}` refuses to touch a non-empty directory.
"""


def write_readme(target, config_path, home, dry_run, log):
    path = os.path.join(target, README_NAME)
    content = render_readme(target, config_path, home)
    try:
        with open(path, encoding="utf-8") as fh:
            current = fh.read()
    except FileNotFoundError:
        current = None
    except OSError as e:
        log.warn(f"cannot read {path}: {e.strerror}")
        return
    if current == content:
        return
    if current is not None and not current.startswith(README_SIGNATURE):
        return  # the user has taken it over
    log.info(f"write: {README_NAME}")
    if dry_run:
        return
    tmp = path + f".{os.getpid()}.tmp"
    try:
        with open(tmp, "w", encoding="utf-8") as fh:
            fh.write(content)
        os.replace(tmp, path)
    except OSError as e:
        _unlink_quiet(tmp)
        log.warn(f"cannot write {path}: {e.strerror}")


