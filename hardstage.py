class Item:
    __slots__ = ("kind", "dev", "ino", "size", "linkto")

    def __init__(self, kind, dev, ino, size, linkto=None):
        self.kind = kind      # "file" or "link"
        self.dev = dev
        self.ino = ino
        self.size = size
        self.linkto = linkto


class ScanResult:
    def __init__(self):
        self.items = {}       # rel -> Item
        self.protected = []   # rels we failed to read; don't prune beneath them
        self.errors = 0


def scan(home, matcher, target, log):
    result = ScanResult()
    target_rel = None
    if target.startswith(home + os.sep):
        target_rel = target[len(home) + 1:]

    def fail(rel, e, what="read"):
        log.error(f"cannot {what} ~/{rel}: {e.strerror or e}")
        result.errors += 1
        result.protected.append(rel)

    def record(rel, path, st):
        if rel in RESERVED_NAMES:
            log.warn(f"~/{rel} collides with a file {PROG} keeps in the "
                     "target root; skipped")
            return
        if stat.S_ISREG(st.st_mode):
            result.items[rel] = Item("file", st.st_dev, st.st_ino, st.st_size)
        elif stat.S_ISLNK(st.st_mode):
            try:
                linkto = os.readlink(path)
            except OSError as e:
                fail(rel, e)
                return
            result.items[rel] = Item("link", st.st_dev, st.st_ino, 0, linkto)
        else:
            log.info(f"skip (not a regular file or symlink): ~/{rel}")

    stack = []
    for root in matcher.roots():
        if target_rel is not None and is_under(root, target_rel):
            log.warn(f"ignoring ~/{root}: it is inside the target directory")
            continue
        path = os.path.join(home, root) if root else home
        try:
            st = os.lstat(path)
        except FileNotFoundError:
            log.info(f"skip (does not exist): ~/{root}")
            continue
        except OSError as e:
            fail(root, e)
            continue
        if stat.S_ISDIR(st.st_mode):
            stack.append((root, matcher.best_for(root, True) if root else -1))
        elif matcher.included(matcher.best_for(root, False)):
            record(root, path, st)

    while stack:
        drel, dbest = stack.pop()
        dpath = os.path.join(home, drel) if drel else home
        try:
            it = os.scandir(dpath)
        except OSError as e:
            fail(drel, e)
            continue
        with it:
            for entry in it:
                rel = join_rel(drel, entry.name)
                try:
                    is_dir = entry.is_dir(follow_symlinks=False)
                except OSError:
                    is_dir = False
                best = matcher.best(rel, entry.name, is_dir, dbest)
                if is_dir:
                    if rel == target_rel:
                        continue
                    if matcher.included(best) or matcher.may_include_below(rel, best):
                        stack.append((rel, best))
                elif matcher.included(best):
                    try:
                        st = entry.stat(follow_symlinks=False)
                    except OSError as e:
                        fail(rel, e)
                        continue
                    record(rel, entry.path, st)
    return result


