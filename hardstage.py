class Busy(Exception):
    """Another hardstage process holds the lock on the target."""


class Log:
    def __init__(self, verbose=False, quiet=False):
        self.verbose = verbose
        self.quiet = quiet

    def info(self, msg):
        if self.verbose:
            print(msg, flush=True)

    def warn(self, msg):
        if not self.quiet:
            print(f"{PROG}: warning: {msg}", file=sys.stderr, flush=True)

    def error(self, msg):
        print(f"{PROG}: error: {msg}", file=sys.stderr, flush=True)


