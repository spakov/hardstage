def join_rel(parent, name):
    return f"{parent}/{name}" if parent else name


def is_under(path, ancestor):
    """True if relative path `path` is `ancestor` or beneath it ("" is the top)."""
    return ancestor == "" or path == ancestor or path.startswith(ancestor + "/")


def expand_path(value, base):
    value = os.path.expanduser(os.path.expandvars(value))
    if not os.path.isabs(value):
        value = os.path.join(base, value)
    return os.path.realpath(value)


def display(path, home):
    if path == home:
        return "~"
    if path.startswith(home + os.sep):
        return "~/" + path[len(home) + 1:]
    return path


def _lstat(path):
    try:
        return os.lstat(path)
    except FileNotFoundError:
        return None


def _unlink_quiet(path):
    try:
        os.unlink(path)
    except FileNotFoundError:
        pass


def human_size(n):
    for unit in ("B", "KiB", "MiB", "GiB", "TiB"):
        if n < 1024 or unit == "TiB":
            return f"{n:.0f} {unit}" if unit == "B" else f"{n:.1f} {unit}"
        n /= 1024.0
    return f"{n} B"


